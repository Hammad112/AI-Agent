def run_agent_turn(
    user_id: int,
    conversation_id: str,
    query: str,
    all_chunks: list[dict],
    business_name: str,
    business_type: str,
) -> dict:
    agent = get_agent()
    initial_state: AgentState = {
        "user_id": user_id,
        "conversation_id": conversation_id,
        "query": query,
        "history": [],
        "all_chunks": all_chunks,
        "retrieved_chunks": [],
        "retrieved_chunk_ids": [],
        "query_topics": [],
        "detected_intents": [],
        "customer_context": {},
        "global_stats": {},
        "tool_results": {},
        "activated_tools": [],
        "response": "",
        "critic_passed": True,
        "critic_feedback": "",
        "business_name": business_name,
        "business_type": business_type,
        "internal_plan": "",
        "conversation_state": {},
    }
    final_state = agent.invoke(initial_state)
    
    # Extract metadata for the frontend
    meta = {}
    for t_name, t_res in final_state.get("tool_results", {}).items():
        if t_name == "confirm_order" and t_res.get("success"):
            meta["order_id"] = t_res.get("order_id")
        elif t_name == "book_appointment" and t_res.get("success"):
            meta["appointment_id"] = t_res.get("booking_id")
            meta["ics_file_url"] = t_res.get("ics_file_url")
        elif t_name == "handle_dispute" and t_res.get("success"):
            meta["complaint_id"] = t_res.get("complaint_id")

    return {
        "response": final_state["response"],
        "detected_intents": final_state.get("detected_intents", []),
        **meta
    }

